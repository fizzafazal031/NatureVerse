    String sunlight,
    String watering,
    String soil,
    String benefits,
    String care,
    String propagation,
    String funFact,
    ) {
  return {
    'id': 'plant_$id',
    'name': name,
    'scientificName': scientificName,
    'type': type,
    'image': image,
    'description': description,
    'details': {
      'Sunlight': sunlight,
      'Watering': watering,
      'Soil Type': soil,
      'Benefits / Uses': benefits,
      'Care Tips': care,
      'Propagation': propagation,
      'Fun Fact': funFact,
    },
  };
}

